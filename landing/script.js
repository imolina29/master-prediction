// ===== Language Switching =====
function setLang(lang) {
  var elements = document.querySelectorAll('[data-i18n]');
  var strings = translations[lang];
  if (!strings) return;

  elements.forEach(function (el) {
    var key = el.getAttribute('data-i18n');
    if (strings[key]) {
      el.textContent = strings[key];
    }
  });

  document.querySelectorAll('.lang-btn').forEach(function (btn) {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  document.documentElement.lang = lang;

  try {
    localStorage.setItem('mp-lang', lang);
  } catch (e) {}
}

// ===== FAQ Accordion =====
function initFAQ() {
  var items = document.querySelectorAll('.faq-item');
  items.forEach(function (item) {
    var question = item.querySelector('.faq-question');
    question.addEventListener('click', function () {
      var isOpen = item.classList.contains('open');
      items.forEach(function (i) {
        i.classList.remove('open');
      });
      if (!isOpen) {
        item.classList.add('open');
      }
    });
  });
}

// ===== Scroll Reveal =====
function initScrollReveal() {
  var reveals = document.querySelectorAll('.reveal');

  var observer = new IntersectionObserver(
    function (entries) {
      entries.forEach(function (entry) {
        if (entry.isIntersecting) {
          entry.target.classList.add('visible');
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.1, rootMargin: '0px 0px -60px 0px' }
  );

  reveals.forEach(function (el, i) {
    var parent = el.parentElement;
    if (parent) {
      var siblings = Array.from(parent.children).filter(function (c) {
        return c.classList.contains('reveal');
      });
      var idx = siblings.indexOf(el);
      if (idx > 0) {
        el.classList.add('reveal-stagger-' + Math.min(idx, 5));
      }
    }
    observer.observe(el);
  });
}

// ===== Animated Stat Counter =====
function initStatCounters() {
  var statValues = document.querySelectorAll('.stat-value[data-target]');
  var animated = false;

  var observer = new IntersectionObserver(
    function (entries) {
      entries.forEach(function (entry) {
        if (entry.isIntersecting && !animated) {
          animated = true;
          animateCounters(statValues);
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.5 }
  );

  var heroStats = document.querySelector('.hero-stats');
  if (heroStats) {
    observer.observe(heroStats);
  }
}

function animateCounters(elements) {
  elements.forEach(function (el) {
    var target = parseInt(el.getAttribute('data-target'), 10);
    var finalText = el.textContent.trim();
    var suffix = finalText.replace(/\d+/, '');
    var duration = 1000;
    var startTime = null;

    function step(timestamp) {
      if (!startTime) startTime = timestamp;
      var progress = Math.min((timestamp - startTime) / duration, 1);
      var eased = 1 - Math.pow(1 - progress, 3);
      var current = Math.round(target * eased);

      el.textContent = current + suffix;

      if (progress < 1) {
        requestAnimationFrame(step);
      } else {
        el.textContent = finalText;
      }
    }

    el.textContent = '0' + suffix;
    requestAnimationFrame(step);
  });
}

// ===== Navbar scroll effect =====
function initNavScroll() {
  var topBar = document.querySelector('.top-bar');
  if (!topBar) return;

  function onScroll() {
    if (window.scrollY > 20) {
      topBar.classList.add('scrolled');
    } else {
      topBar.classList.remove('scrolled');
    }
  }

  window.addEventListener('scroll', onScroll, { passive: true });
  onScroll();
}

// ===== Smooth scroll for anchor links =====
function initSmoothScroll() {
  document.querySelectorAll('a[href^="#"]').forEach(function (a) {
    a.addEventListener('click', function (e) {
      var target = document.querySelector(a.getAttribute('href'));
      if (target) {
        e.preventDefault();
        target.scrollIntoView({ behavior: 'smooth', block: 'start' });
      }
    });
  });
}

// ===== Init =====
document.addEventListener('DOMContentLoaded', function () {
  document.querySelectorAll('.lang-btn').forEach(function (btn) {
    btn.addEventListener('click', function () {
      setLang(btn.getAttribute('data-lang'));
    });
  });

  var savedLang = 'en';
  try {
    savedLang = localStorage.getItem('mp-lang') || 'en';
  } catch (e) {}
  setLang(savedLang);

  initFAQ();
  initScrollReveal();
  initStatCounters();
  initNavScroll();
  initSmoothScroll();
});
